#include <string.h>

static int failures;

#define FAIL(fmt, ...) do { \
	fprintf(stderr, "FAIL %s:%d " fmt "\n", __func__, __LINE__, ##__VA_ARGS__); \
	failures++; \
} while (0)

#define OK(label) printf("ok   %s\n", (label))

#define EXPECT_EQ(actual, expected, label) do { \
	if ((actual) != (expected)) \
		FAIL("%s: got %u expected %u", (label), \
		     (unsigned)(actual), (unsigned)(expected)); \
	else OK(label); \
} while (0)

/* ------------------------------------------------------------------ */
/* Flat 16 MB memory with big-endian bus callbacks                    */
/* ------------------------------------------------------------------ */

#define MEM_SIZE (16 * 1024 * 1024)
static uint8_t mem[MEM_SIZE];

static uint32_t
mem_read8(void *ctx, uint32_t addr)
{
	(void)ctx;
	if (addr < MEM_SIZE)
		return mem[addr];
	return 0;
}

static uint32_t
mem_read16(void *ctx, uint32_t addr)
{
	(void)ctx;
	if (addr + 1 < MEM_SIZE)
		return ((uint32_t)mem[addr] << 8) | mem[addr + 1];
	return 0;
}

static uint32_t
mem_read32(void *ctx, uint32_t addr)
{
	(void)ctx;
	if (addr + 3 < MEM_SIZE)
		return ((uint32_t)mem[addr] << 24) |
		       ((uint32_t)mem[addr + 1] << 16) |
		       ((uint32_t)mem[addr + 2] << 8) |
		       mem[addr + 3];
	return 0;
}

static void
mem_write8(void *ctx, uint32_t addr, uint32_t val)
{
	(void)ctx;
	if (addr < MEM_SIZE)
		mem[addr] = val & 0xFF;
}

static void
mem_write16(void *ctx, uint32_t addr, uint32_t val)
{
	(void)ctx;
	if (addr + 1 < MEM_SIZE) {
		mem[addr]     = (val >> 8) & 0xFF;
		mem[addr + 1] = val & 0xFF;
	}
}

static void
mem_write32(void *ctx, uint32_t addr, uint32_t val)
{
	(void)ctx;
	if (addr + 3 < MEM_SIZE) {
		mem[addr]     = (val >> 24) & 0xFF;
		mem[addr + 1] = (val >> 16) & 0xFF;
		mem[addr + 2] = (val >> 8) & 0xFF;
		mem[addr + 3] = val & 0xFF;
	}
}

